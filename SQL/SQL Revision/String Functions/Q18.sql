

-- Q18. Pad +91 in the phone number from the left?

SELECT LPAD(" 1234567890",14,"+91"); -- +91 1234567890

SELECT LPAD("1234567890",13,"+91"); -- +911234567890

SELECT LPAD("1234567890",12,"+91"); -- +91234567890

SELECT LPAD("1234567890",10,"+91"); -- 1234567890

SELECT LPAD("1234567890",14,"+91"); -- +91+1234567890

SELECT LPAD("1234567890",15,"+91"); -- +91+91234567890

SELECT LPAD("1234567890",16,"+91"); -- +91+911234567890

SELECT LPAD("1234567890",17,"+91"); -- +91+91+1234567890

SELECT LPAD("1234567890",18,"+91"); -- +91+91+91234567890