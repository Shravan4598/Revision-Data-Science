

-- Q19. Pad +91 in the phone number from the RIGHT?


SELECT RPAD(" 1234567890",14,"+91"); --  1234567890+91

SELECT RPAD("1234567890",13,"+91"); -- 1234567890+91

SELECT RPAD("1234567890",12,"+91"); -- 1234567890+9

SELECT RPAD("1234567890",10,"+91"); -- 1234567890

SELECT RPAD("1234567890",14,"+91"); -- 1234567890+91+

SELECT RPAD("1234567890",15,"+91"); -- 1234567890+91+9

SELECT RPAD("1234567890",16,"+91"); -- 1234567890+91+91

SELECT RPAD("1234567890",17,"+91"); -- 1234567890+91+91+

SELECT RPAD("1234567890",18,"+91"); -- 1234567890+91+91+9